class ImageNetMultiViewDataset(torch.utils.data.Dataset):
    def __init__(self, base_dataset, num_views=cfg.num_views, train=True):
        self.ds = base_dataset
        self.num_views = num_views
        self.transform = train_transform if train else test_transform

    def __len__(self):
        return len(self.ds)

    def __getitem__(self, idx):

        try:
            img, label = self.ds[idx]
        except Exception as e:
            print(f"Skipping corrupted image at idx={idx}: {e}")

            new_idx = (idx + 1) % len(self.ds)
            img, label = self.ds[new_idx]

        img = img.convert("RGB")

        if self.num_views > 1:
            global_views = [train_transform(img) for _ in range(2)]
            local_views = [local_transform(img) for _ in range(4)]
            views = global_views + local_views
        else:
            views = test_transform(img)

        return views, label

